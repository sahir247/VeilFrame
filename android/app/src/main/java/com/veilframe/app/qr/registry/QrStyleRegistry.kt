/**
 * Authoritative specification of a QR visual style, binding renderer implementation,
 * default module/finder geometry, and aesthetic capabilities.
 */
data class QrStyleDefinition(
    val style: QrStyle,
    val displayName: String,
    val defaultModuleShape: ModuleShape,
    val defaultFinderStyle: FinderStyle,
    val is25D: Boolean = false,
    val imageFillMode: Boolean = false,
    val requiresBackgroundImage: Boolean = false,
    val requiresSourceImage: Boolean = false,
    val supportsGradients: Boolean = true,
    val supportsDataShape: Boolean = true,
    val supportsDataScale: Boolean = true,
    val supportsFinderStyle: Boolean = true,
    val supportsFinderColors: Boolean = true,
    val supportsTimingAndAlignment: Boolean = true,
    val supportsForegroundColor: Boolean = true,
    val supportsBackgroundColor: Boolean = true,
    val supportsBackgroundImage: Boolean = false,
    val supportsBackdropCard: Boolean = true,
    val supportsSourceImage: Boolean = false,
    val supportsAnimatedSource: Boolean = false,
    val supportsAnimatedLogo: Boolean = true,
    val rendererFactory: () -> QrRenderer
)

